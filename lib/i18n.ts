export function translate(lang: Lang, key: Key): string {
  if (lang === 'en') return EN[key]
  return L[lang][key] ?? EN[key]
}

// Reads the current language and returns a translate function; re-renders when the language changes.
export function useT() {
  const lang = useStore((s) => s.lang)
  return (key: Key) => translate(lang, key)
}

// A title with a coloured last part: "Certified by |the best." -> [plain, accent]
export const split = (s: string) => s.split('|')

// The language to start in: what the person chose last time, else the browser's own language, else English.
export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem('radoya-lang')
    if (isLang(saved)) return saved
  } catch {
    // storage unavailable
  }
  for (const l of navigator.languages || [navigator.language]) {
    const code = (l || '').slice(0, 2).toLowerCase()
    if (isLang(code)) return code
  }
  return 'en'
}
